import { createHash } from "node:crypto";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, extname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { gunzipSync } from "node:zlib";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const registryPath = resolve(root, "metadata/sources.json");
const jsonOutputPath = resolve(root, "metadata/source-provenance.generated.json");
const tsOutputPath = resolve(root, "app/source-provenance.generated.ts");
const checkOnly = process.argv.includes("--check");
const allowedConfidence = new Set(["official", "primary-mixed", "internal-derived"]);
const allowedUseStatus = new Set(["accepted", "experimental", "display-only", "validation-only", "gap-tracked", "derived"]);

function fail(message) {
  throw new Error(`source provenance: ${message}`);
}

function readText(path) {
  const bytes = readFileSync(path);
  return extname(path) === ".gz" ? gunzipSync(bytes).toString("utf8") : bytes.toString("utf8");
}

function recordCount(path) {
  const name = path.replace(/\.gz$/, "");
  if (name.endsWith(".csv")) {
    const text = readText(path).trim();
    return text ? Math.max(0, text.split(/\r?\n/).length - 1) : 0;
  }
  if (name.endsWith(".json")) {
    const value = JSON.parse(readText(path));
    return Array.isArray(value) ? value.length : null;
  }
  return null;
}

function artifactMetadata(relativePath) {
  const path = resolve(root, relativePath);
  if (!existsSync(path)) fail(`missing declared artifact ${relativePath}`);
  const bytes = readFileSync(path);
  return {
    path: relativePath,
    sha256: createHash("sha256").update(bytes).digest("hex"),
    bytes: bytes.length,
    records: recordCount(path),
  };
}

const registry = JSON.parse(readFileSync(registryPath, "utf8"));
if (registry.schemaVersion !== 1 || !Array.isArray(registry.sources)) fail("unsupported registry schema");
const seenIds = new Set();
for (const source of registry.sources) {
  if (!source.id || seenIds.has(source.id)) fail(`duplicate or missing source id ${source.id ?? "<missing>"}`);
  seenIds.add(source.id);
  if (!allowedConfidence.has(source.confidence)) fail(`${source.id}: unsupported confidence ${source.confidence}`);
  if (!allowedUseStatus.has(source.useStatus)) fail(`${source.id}: unsupported use status ${source.useStatus}`);
  if (!source.canonicalUrl?.startsWith("https://")) fail(`${source.id}: canonical URL must use HTTPS`);
  if (!Array.isArray(source.localArtifacts) || source.localArtifacts.length === 0) fail(`${source.id}: no local artifacts declared`);
}

const sources = registry.sources.map((source) => ({
  ...source,
  artifacts: source.localArtifacts.map(artifactMetadata),
}));
const artifactCount = sources.reduce((sum, source) => sum + source.artifacts.length, 0);
const officialCount = sources.filter((source) => source.confidence === "official").length;
const criticalCount = sources.filter((source) => source.criticalToForecast).length;
const manifest = {
  schemaVersion: 1,
  registryReviewedAt: registry.registryReviewedAt,
  summary: {
    sourceGroups: sources.length,
    officialSourceGroups: officialCount,
    criticalSourceGroups: criticalCount,
    tracedArtifacts: artifactCount,
    automationStatus: "scheduled-freshness-monitoring",
  },
  sources,
};
const json = `${JSON.stringify(manifest, null, 2)}\n`;
const ts = `// Generated by scripts/generate-source-provenance.mjs. Do not edit by hand.\nexport const sourceProvenance = ${JSON.stringify(manifest, null, 2)} as const;\n`;

if (checkOnly) {
  if (!existsSync(jsonOutputPath) || readFileSync(jsonOutputPath, "utf8") !== json) fail("generated JSON is stale; run npm run data:provenance");
  if (!existsSync(tsOutputPath) || readFileSync(tsOutputPath, "utf8") !== ts) fail("generated TypeScript is stale; run npm run data:provenance");
  console.log(`Verified ${sources.length} source groups and ${artifactCount} traced artifacts.`);
} else {
  writeFileSync(jsonOutputPath, json);
  writeFileSync(tsOutputPath, ts);
  console.log(`Generated provenance for ${sources.length} source groups and ${artifactCount} traced artifacts.`);
}
