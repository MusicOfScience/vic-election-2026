import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const eventsPath = resolve(root, "model/data/processed/poll_events_seed.csv");
const estimatesPath = resolve(root, "model/data/processed/poll_estimates_seed.csv");
const outputPath = resolve(root, "app/poll-data.generated.ts");
const checkOnly = process.argv.includes("--check");

function parseCsv(text) {
  const rows = [];
  let row = [], value = "", quoted = false;
  for (let index = 0; index < text.length; index += 1) {
    const char = text[index];
    if (char === '"' && quoted && text[index + 1] === '"') { value += '"'; index += 1; }
    else if (char === '"') quoted = !quoted;
    else if (char === "," && !quoted) { row.push(value); value = ""; }
    else if ((char === "\n" || char === "\r") && !quoted) {
      if (char === "\r" && text[index + 1] === "\n") index += 1;
      row.push(value); value = "";
      if (row.some((cell) => cell !== "")) rows.push(row);
      row = [];
    } else value += char;
  }
  if (value || row.length) { row.push(value); rows.push(row); }
  const header = rows.shift();
  return rows.map((cells) => Object.fromEntries(header.map((name, index) => [name, cells[index] ?? ""])));
}

const events = parseCsv(readFileSync(eventsPath, "utf8"));
const estimates = parseCsv(readFileSync(estimatesPath, "utf8"));
const estimatesByPoll = Map.groupBy(estimates, (row) => row.poll_id);
const parties = ["ALP", "LIB_NAT", "ONP", "GRN"];
const polls = events.filter((event) => event.model_eligible === "True").map((event) => {
  const rows = estimatesByPoll.get(event.poll_id) ?? [];
  const value = (party) => rows.filter((row) => party === "OTH_IND" ? ["OTH", "IND", "OTH_IND"].includes(row.party_id) : row.party_id === party).reduce((sum, row) => sum + Number(row.primary_pct), 0);
  const shares = Object.fromEntries([...parties, "OTH_IND"].map((party) => [party, value(party)]));
  const total = Object.values(shares).reduce((sum, share) => sum + share, 0);
  if (Math.abs(total - 100) > .01) throw new Error(`${event.poll_id}: eligible poll shares total ${total}, not 100`);
  const date = new Date(`${event.fieldwork_end}T00:00:00Z`);
  return {
    id: event.poll_id,
    date: `${date.getUTCDate()} ${date.toLocaleString("en-AU", { month: "short", timeZone: "UTC" })}`,
    fieldworkStart: event.fieldwork_start,
    fieldworkEnd: event.fieldwork_end,
    publicationDate: event.publication_date,
    pollster: event.pollster,
    commissioner: event.commissioner || null,
    n: Number(event.sample_size),
    effectiveN: event.effective_sample_size ? Number(event.effective_sample_size) : null,
    method: event.method,
    voteBase: event.vote_base,
    verificationStatus: event.verification_status,
    sourceTier: event.source_tier,
    sourceUrl: event.source_url || null,
    sourceDocumentTitle: event.source_document_title || null,
    alp: shares.ALP,
    coalition: shares.LIB_NAT,
    onp: shares.ONP,
    greens: shares.GRN,
    other: shares.OTH_IND,
  };
}).sort((a, b) => a.fieldworkEnd.localeCompare(b.fieldworkEnd));

if (polls.length !== 9) throw new Error(`expected 9 eligible polls, found ${polls.length}`);
const output = `// Generated by scripts/generate-poll-data.mjs. Do not edit by hand.\nexport const pollSeries = ${JSON.stringify(polls, null, 2)} as const;\n`;
if (checkOnly) {
  if (!existsSync(outputPath) || readFileSync(outputPath, "utf8") !== output) throw new Error("generated poll data is stale; run npm run data:polls");
  console.log(`Verified ${polls.length} canonical eligible polls.`);
} else {
  writeFileSync(outputPath, output);
  console.log(`Generated ${polls.length} canonical eligible polls.`);
}
