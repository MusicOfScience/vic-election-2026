import fs from "node:fs";
import path from "node:path";

const root = path.resolve(process.argv[2] || "model-source");
const processed = path.join(root, "data", "processed");

function parseLine(line) {
  const cells = [];
  let value = "";
  let quoted = false;
  for (let index = 0; index < line.length; index += 1) {
    const char = line[index];
    if (char === '"' && line[index + 1] === '"' && quoted) {
      value += '"';
      index += 1;
    } else if (char === '"') {
      quoted = !quoted;
    } else if (char === "," && !quoted) {
      cells.push(value);
      value = "";
    } else {
      value += char;
    }
  }
  cells.push(value);
  return cells;
}

function readCsv(fileName) {
  const lines = fs.readFileSync(path.join(processed, fileName), "utf8").trim().split(/\r?\n/);
  const header = parseLine(lines.shift());
  return lines.map((line) => Object.fromEntries(parseLine(line).map((value, index) => [header[index], value])));
}

const cycles = [
  {
    label: "2002–06",
    file: "vec_2002_2006_same_boundary_tpp_swing.csv",
    swing: "alp_tpp_swing_2002_2006",
    start: "alp_tpp_share_2002",
    end: "alp_tpp_share_2006",
    comparison: "Same boundaries",
  },
  {
    label: "2006–10",
    file: "vec_2006_2010_same_boundary_tpp_swing.csv",
    swing: "alp_tpp_swing_2006_2010",
    start: "alp_tpp_share_2006",
    end: "alp_tpp_share_2010",
    comparison: "Same boundaries",
  },
  {
    label: "2010–14",
    file: "vec_2010_2014_redistribution_adjusted_tpp_swing.csv",
    swing: "alp_tpp_swing_2010_2014",
    start: "estimated_2010_alp_tpp_share_on_2014_boundary",
    end: "alp_tpp_share_2014",
    comparison: "Redistribution-adjusted",
  },
  {
    label: "2014–18",
    file: "vec_2014_2018_same_boundary_tpp_swing.csv",
    swing: "alp_tpp_swing_2014_2018",
    start: "alp_tpp_share_2014",
    end: "alp_tpp_share_2018",
    comparison: "Same boundaries",
  },
];

const history = new Map();
for (const cycle of cycles) {
  for (const row of readCsv(cycle.file)) {
    const entries = history.get(row.district_name) ?? [];
    entries.push({
      cycle: cycle.label,
      alpStart: Number(row[cycle.start]) * 100,
      alpEnd: Number(row[cycle.end]) * 100,
      alpSwing: Number(row[cycle.swing]) * 100,
      comparison: cycle.comparison,
    });
    history.set(row.district_name, entries);
  }
}

const current = readCsv("vec_2022_all_district_tpp.csv");
const estimated2018 = new Map(readCsv("vec_2018_estimated_2022_boundary_2cp.csv").map((row) => [row.district_name, row]));
const districts = current.map((row) => {
  const entries = history.get(row.district_name) ?? [];
  const prior = estimated2018.get(row.district_name);
  const baseline = prior?.estimated_2018_alp_tpp_share_on_2022_boundary;
  if (baseline && row.state_alp_tpp_share) {
    const start = Number(baseline) * 100;
    const end = Number(row.state_alp_tpp_share) * 100;
    entries.push({ cycle: "2018–22", alpStart: start, alpEnd: end, alpSwing: end - start, comparison: "Estimated on 2022 boundaries" });
  }
  return {
    districtId: row.district_id,
    districtName: row.district_name,
    alpTpp2022: Number(row.state_alp_tpp_share) * 100,
    coalitionTpp2022: Number(row.state_coalition_tpp_share) * 100,
    tppFormalVotes2022: Number(row.state_tpp_formal_votes),
    tppMethod2022: row.vec_tpp_method,
    cycles: entries,
  };
});

const output = `// Generated by scripts/generate-historical-data.mjs\nexport const historicalDistricts = ${JSON.stringify(districts, null, 2)} as const;\n`;
fs.writeFileSync(path.resolve("app/historical-data.generated.ts"), output);
console.log(`Generated ${districts.length} district histories.`);
