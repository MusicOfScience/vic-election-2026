"use client";

import { useMemo, useState } from "react";
import { modelOutput } from "./model-output.generated";
import candidateRoster from "./vec-official-candidates-2026.review.json";
import review from "../metadata/november-poll-evidence-review-2026-11-11.json";
type Evidence = {
  id: string; scope: string; pollster: string; commissioner: string;
  reportedDates: {start: string; end: string | null};
  reportedSampleSize: number; effectiveSampleSize: number | null;
  reportedPrimaries?: Partial<Record<"alp" | "coalition" | "onp" | "greens", number>>;
  reportedCandidatePrimaries?: Partial<Record<"onpPickering" | "libDyson" | "alpSoliven" | "greensYawari", number>>;
  reportedTwoCandidatePreferred?: { onpPickering: number; libDyson: number; status: string };
  sourceUrl: string;
};
const waves: Evidence[] = review.evidence as Evidence[];


type ModelSeat = (typeof modelOutput.districts)[number];
type CandidateRow = [string, string, number, string, string | null];
const rows = candidateRoster.rows as CandidateRow[];
const candidatesByDistrict = new Map<string, CandidateRow[]>();
for (const row of rows) {
  if (row[0] !== "Assembly") continue;
  const prior = candidatesByDistrict.get(row[1]) ?? [];
  prior.push(row);
  candidatesByDistrict.set(row[1], prior);
}

const registeredFamily = (party: string | null) => {
  if (party === "Australian Labor Party - Victorian Branch") return "ALP";
  if (party === "Liberal Party of Australia - Victorian Division" ||
      party === "National Party of Australia - Victoria") return "LIB_NAT";
  if (party === "One Nation Victoria") return "ONP";
  if (party === "Australian Greens Victoria") return "GRN";
  return "OTH_IND";
};

const pct = (probability: number) => (probability * 100).toFixed(1) + "%";
const pp = (value: number) => value.toFixed(1) + "%";
const pakenham = waves.find((x) => x.id === "pakenham-2026-11-04-08-demosau-primary");
const fallback = "Not published";

export function NovemberPollingEvidence() {
  return <section className="surface november-evidence" aria-label="November polling evidence review">
    <div className="november-review-header">
      <p className="eyebrow">November evidence · 11 November review</p>
      <h3>Published polling, not yet admitted</h3>
      <p>Four new evidence leads are recorded below. The two newest statewide polling waves have not passed the original source-methodology and owner-admission contract. These are observed polling reports, not predictions generated by our model.</p>
    </div>
    <div className="november-evidence-items">
      {waves.map((wave) => <article key={wave.id} className="november-evidence-item">
        <div className="november-evidence-item-heading">
          <strong>{wave.pollster}</strong>
          <span>{wave.scope === "assembly_district" ? "Pakenham electorate" : "Victoria statewide"}</span>
        </div>
        <p>Fieldwork {wave.reportedDates.start} to {wave.reportedDates.end ?? "unresolved"} · sample {wave.reportedSampleSize.toLocaleString("en-AU")}{wave.effectiveSampleSize ? ` (effective ${wave.effectiveSampleSize})` : ""}</p>
        {wave.scope === "state_assembly" && <div className="november-evidence-numbers">
          {(["alp", "coalition", "onp", "greens"] as const).map((key) => <span key={key}><b>{wave.reportedPrimaries?.[key] ?? "—"}%</b><small>{{alp:"Labor", coalition:"Coalition", onp:"One Nation", greens:"Greens"}[key]}</small></span>)}
        </div>}
        {wave.scope === "assembly_district" && <div className="november-evidence-numbers">
          {(["onpPickering", "libDyson", "alpSoliven", "greensYawari"] as const).map((key) => <span key={key}><b>{wave.reportedCandidatePrimaries?.[key] ?? "—"}%</b><small>{{onpPickering:"ONP", libDyson:"Liberal", alpSoliven:"Labor", greensYawari:"Greens"}[key]}</small></span>)}
        </div>}
        {wave.id.startsWith("resolve-") && <p className="november-evidence-warning">Fieldwork end disputed: 5 or 7 November. The Victorian sample is not an additional independent sample from the associated federal survey.</p>}
        {wave.id.startsWith("demosau-") && <p className="november-evidence-warning">The remaining 11 points are an arithmetic residual, not a separately verified published Others figure. November effective sample size is unknown.</p>}
        {wave.id.startsWith("lighthouse-") && <p className="november-evidence-warning">Rolling two-week tracker; adjacent waves are dependent. A News Corp account gives Labor 22%, One Nation 23%, while an early Poll Bludger summary reversed those two figures. The disagreement is retained in the source record.</p>}
        {wave.id.startsWith("pakenham-") && <p className="november-evidence-warning">The published 50–50 two-candidate comparison is modelled using assumed preference flows, not a measured final count or a seat-win probability.</p>}
        <p className="november-evidence-status">Evidence: under review · canonical model: not admitted at the 11 November assessment</p>
        <a href={wave.sourceUrl} rel="noreferrer" target="_blank">Open supporting publication</a>
      </article>)}
    </div>
    <p className="november-evidence-footnote">Polls above come from differently sourced publications. Full wave-level effective sample sizes, uncertainty, respondent overlap, and undecided treatment must be adjudicated separately. A voter-intention survey cannot be used as if it were an election result. Current reference forecast date: {modelOutput.manifest.as_of}.</p>
  </section>;
}

export function SeatIntegrityEvidence() {
  const [view, setView] = useState<"all" | "onp" | "other" | "local">("all");
  const selected = useMemo(() => modelOutput.districts.filter((seat) => {
    const major = seat.win_onp >= .80;
    const collapsed = seat.primary_oth_ind >= 20 && seat.win_oth_ind < .01;
    const local = seat.district_name === "Pakenham";
    if (view === "onp") return major;
    if (view === "other") return collapsed;
    if (view === "local") return local;
    return major || collapsed || local;
  }).sort((a, b) => a.district_name.localeCompare(b.district_name)), [view]);
  const allFamiliesNominated = modelOutput.districts.every((d) => {
    const list = candidatesByDistrict.get(d.district_name) ?? [];
    const names = new Set(list.map((r) => registeredFamily(r[4])));
    return ["ALP","LIB_NAT","ONP","GRN","OTH_IND"].every((p) => names.has(p));
  });
  const pakenhamModel = modelOutput.districts.find((x) => x.district_name === "Pakenham");
  const pakenhamPoll = pakenham?.reportedCandidatePrimaries?.onpPickering ?? 0;
  const overlapUnknown = pakenham?.effectiveSampleSize ?? 0;
  const gap = pakenhamModel ? pakenhamPoll - pakenhamModel.primary_onp : 0;

  return <section className="surface seat-integrity" aria-label="High-confidence seat model integrity audit">
    <div className="seat-integrity-header">
      <p className="eyebrow">Mechanics audit · frozen reference model</p>
      <h3>Where the model warrants scepticism</h3>
      <p>These are reproducible flags from the existing {modelOutput.manifest.as_of} experimental output, checked against the VEC’s 1,037 officially nominated candidates. They are <strong>not</strong> empirical errors, newly adjusted probabilities or recommendations on how to vote.</p>
    </div>
    <div className="seat-integrity-summary">
      <article><strong>{modelOutput.districts.filter((d) => d.win_onp >= .80).length}</strong><span>ONP win frequencies ≥80%</span></article>
      <article><strong>{modelOutput.districts.filter((d) => d.primary_oth_ind >=20 && d.win_oth_ind <.01).length}</strong><span>High residual primary; negligible residual wins</span></article>
      <article><strong>{allFamiliesNominated ? "88/88" : "Review"}</strong><span>Electorates with all five broad families nominated</span></article>
    </div>
    <div className="seat-integrity-control">
      <label htmlFor="seat-risk-mode">Audit category</label>
      <select id="seat-risk-mode" value={view} onChange={(e) => setView(e.target.value as typeof view)}>
        <option value="all">All flagged electorates</option>
        <option value="onp">High One Nation win frequencies</option>
        <option value="other">Collapsed Others/independent family</option>
        <option value="local">Pakenham local-poll discrepancy</option>
      </select>
    </div>
    <div className="seat-integrity-table-wrap"><table className="seat-integrity-table">
      <thead><tr><th>Electorate</th><th>Party / model family</th><th>Model primary</th><th>Win frequency</th><th>VEC nominees in family</th></tr></thead>
      <tbody>{selected.map((seat: ModelSeat) => {
        const isOther = seat.primary_oth_ind >= 20 && seat.win_oth_ind < .01;
        const family = isOther ? "OTH_IND" : "ONP";
        const list = candidatesByDistrict.get(seat.district_name) ?? [];
        const familyCandidates = list.filter((r) => registeredFamily(r[4]) === family);
        const onp = family === "ONP";
        return <tr key={seat.district_id}>
          <th scope="row">{seat.district_name}<small>{seat.likely_final_pair.replaceAll("_", " ")}</small></th>
          <td>{onp ? "One Nation" : "Others / independents"}</td>
          <td>{pp(onp ? seat.primary_onp : seat.primary_oth_ind)}</td>
          <td>{pct(onp ? seat.win_onp : seat.win_oth_ind)}</td>
          <td>{familyCandidates.length}<small>{familyCandidates.length > 1 ? "Individual candidates aggregated" : "Nominee verified"}</small></td>
        </tr>;
      })}</tbody>
    </table></div>
    <div className="seat-integrity-explanation">
      <article>
        <h4>1 · Candidate availability is not the problem</h4>
        <p>Official VEC nominations include all five model families in every Assembly electorate. But one family may contain multiple individually competing candidates. The model’s five-family preferential count treats Others/independents as <strong>one</strong> contender; in Ripon, Liberal and National nominees also compete separately. This can alter elimination order and the final pair.</p>
      </article>
      <article>
        <h4>2 · The transfer assumptions favour some paths</h4>
        <p>In the model’s fixed preference prior, an eliminated Coalition family allocates 51% of its starting transfer weights to One Nation and 26% to Labor. Conditional on a final pair consisting only of One Nation and Labor, this renormalises to roughly <strong>66% for One Nation</strong>. That is model arithmetic, not a measured 2026 voter preference flow. Concentration 72 limits dispersion, and independent historical testing found that this level of confidence is questionable.</p>
      </article>
      <article>
        <h4>3 · The One Nation geographical limit has an exception</h4>
        <p>The model configuration lists a One Nation local log-odds bound of ±0.45, but the calculation later overrides it with an AEC-derived One Nation geographical pattern capped at −1.20 to +1.10. The higher effective positive bound permits a relative-odds multiplier of about 3.0, versus 1.57 under ±0.45. This is a code-level observation, <strong>not proof of a programming error</strong>. The reference model has not been altered.</p>
      </article>
      <article>
        <h4>4 · One local observation challenges Pakenham</h4>
        <p>The October model gives Pakenham One Nation {pakenhamModel ? pp(pakenhamModel.primary_onp) : fallback} primary and {pakenhamModel ? pct(pakenhamModel.win_onp) : fallback} winning frequency. A separately published 4–8 November electorate survey reports {pakenhamPoll}% One Nation primary, about <strong>{gap.toFixed(1)} percentage points higher</strong> than the older model’s primary estimate. Its effective sample is {overlapUnknown}; its two-candidate result uses assumed transfers. This is a useful diagnostic discrepancy, <strong>not</strong> an independent calibration test or authorised forecast refresh.</p>
        <a href={pakenham?.sourceUrl ?? "https://demosau.com/"} rel="noreferrer" target="_blank">Read the Pakenham electorate poll</a>
      </article>
    </div>
  </section>;
}
